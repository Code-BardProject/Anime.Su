const LOCAL_ANIME_KEY = "animeSuLocalAnime";
const VIEWED_EPISODE_KEY = "animeSuViewedEpisode";

export const getStoredAnime = (): any[] => {
  if (typeof window === "undefined") return [];

  try {
    const stored = JSON.parse(localStorage.getItem(LOCAL_ANIME_KEY) || "[]");
    return Array.isArray(stored) ? stored : [];
  } catch {
    return [];
  }
};

const persistAnimeList = () => {
  if (typeof window === "undefined") return;

  try {
    localStorage.setItem(LOCAL_ANIME_KEY, JSON.stringify(animeList));
  } catch (error) {
    console.warn("Не удалось сохранить локальный каталог аниме:", error);
  }
};

export const incrementAnimeViews = (animeId: number | string, episode = 1) => {
  if (typeof window === "undefined") return;

  const viewKey = `${String(animeId)}:${episode}`;
  try {
    const viewedEpisodes = JSON.parse(sessionStorage.getItem(VIEWED_EPISODE_KEY) || "[]");
    if (Array.isArray(viewedEpisodes) && viewedEpisodes.includes(viewKey)) return;
    sessionStorage.setItem(VIEWED_EPISODE_KEY, JSON.stringify([
      ...(Array.isArray(viewedEpisodes) ? viewedEpisodes : []),
      viewKey,
    ]));
  } catch {
    return;
  }

  const anime = animeList.find((item) => String(item.id) === String(animeId));
  if (!anime) return;

  anime.views = Number(anime.views || 0) + 1;
  persistAnimeList();
  window.dispatchEvent(new CustomEvent("animeSu:views-updated", {
    detail: { animeId: anime.id, views: anime.views },
  }));
};

